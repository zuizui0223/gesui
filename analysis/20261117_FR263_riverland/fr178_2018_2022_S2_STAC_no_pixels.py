def sha(b):return hashlib.sha256(b).hexdigest()

def source_sites(geo):
    # Input CSV generated by exact signed original source-only 263 riverline
    # and original real 2018+2022 positive TP sampling-month intersection.
    rows=pd.read_csv(geo,dtype={"site_key":str,"HYRIV_ID":str,"H7":str,"H6":str})
    if len(rows)!=178 or rows.site_key.nunique()!=178 or rows.H7.nunique()!=58 or rows.H6.nunique()!=23:
        raise RuntimeError("Original fixed FR178 source population changed")
    if (rows.n_original_JJA_same_calendar_months<2).any() or \
        not (rows.original_station_to_original_reach_m<=250).all() or \
        not (rows.original_along_reach_window_length_m>=900).all():
        raise RuntimeError("True physical reach + same-month TP prerequisites not met")
    if not (rows.eea_lat.between(44,51).all() and rows.eea_lon.between(-6,10).all()):
        raise RuntimeError("Original site coordinate outside source-supported mainland")
    return rows.rename(columns={"eea_lat":"lat","eea_lon":"lon"})


def bbox(r,metres=1750):
    lat=float(r.lat);lon=float(r.lon)
    dlat=metres/111132.0
    dlon=metres/(111320.0*math.cos(math.radians(lat)))
    return [lon-dlon,lat-dlat,lon+dlon,lat+dlat]

def search_scenes(session,r,year):
    geom=bbox(r)
    query={
      "collections":[COLLECTION],
      "bbox":geom,
      "datetime":f"{year}-05-01T00:00:00Z/{year}-09-30T23:59:59Z",
      "query":{"eo:cloud_cover":{"lte":40}},
      "limit":100}
    all_items=[];seen=set();url=API;method="POST";body=query
    for page in range(7):
        for attempt in range(4):
            try:
                x=session.post(url,json=body,timeout=(15,80)) if method=="POST" else \
                  session.get(url,timeout=(15,80))
                if x.status_code in (429,500,502,503,504):
                    raise requests.RequestException("Transient STAC status="+str(x.status_code))
                x.raise_for_status()
                parsed=x.json()
                if not isinstance(parsed.get("features"),list):
                    raise RuntimeError("Not STAC feature list")
                break
            except (requests.RequestException,ValueError,RuntimeError) as e:
                if attempt==3:raise RuntimeError("Source STAC read unavailable: "+str(e))
                time.sleep(2+attempt*2)
        for item in parsed["features"]:
            if item.get("id") not in seen:
                all_items.append(item);seen.add(item.get("id"))
        nextp=next((a for a in parsed.get("links",[]) if a.get("rel")=="next"),None)
        if not nextp:break
        url=nextp.get("href","")
        if not url.startswith("https://earth-search.aws.element84.com/"):
            raise RuntimeError("Unexpected STAC next-page URL")
        method=nextp.get("method","GET").upper()
        body=nextp.get("body",{})
        if method not in ("GET","POST"):raise RuntimeError("STAC next pagination method unsupported")
    else:raise RuntimeError("STAC pagination >7 pages; stop source")
    out=[]
    for it in all_items:
        props=it.get("properties",{})
        dt=str(props.get("datetime",""))
        if not dt.startswith(str(year)+"-"):continue
        try:month=int(dt[5:7]);cloud=float(props["eo:cloud_cover"])
        except (ValueError,KeyError,TypeError):continue
        if month not in MONTHS or cloud<0 or cloud>40:continue
        if it.get("collection")!=COLLECTION or not it.get("geometry"):continue
        try:
            if not shape(it["geometry"]).covers(box(*geom)):continue
        except ValueError:continue
        assets=it.get("assets",{});item_bands={}
        for k in ("red","nir","scl"):
            a=assets.get(k,{})
            href=a.get("href","")
            if not isinstance(href,str) or not href.startswith("https://sentinel-cogs.s3.us-west-2.amazonaws.com/") or not href.endswith(".tif"):
                break
            rb=a.get("raster:bands") or []
            if k!="scl" and (len(rb)!=1 or "scale" not in rb[0]):
                break
            item_bands[k]={"href":href,"raster_bands":rb[:1]}
        if len(item_bands)!=3:continue
        out.append({"scene_id":it.get("id"),"datetime":dt,"month":month,
             "cloud_pct":cloud,"bands":item_bands})
    picks=[]
    for m in MONTHS:
        group=sorted((a for a in out if a["month"]==m),
                     key=lambda a:(a["cloud_pct"],a["datetime"],a["scene_id"]))[:2]
        picks.extend(group)
    return {"stac_items_received":len(all_items),
            "valid_original_items":len(out),
            "selected_months":sorted({x["month"] for x in picks}),
            "source_selected_scenes":picks}

def run(args):
    chosen=source_sites(args.geo).sort_values("site_key")
    sess=requests.Session()
    sess.headers.update({"User-Agent":"gesui-fr178-20261117-river-jja-s2-real-stac/1",
                         "Accept":"application/geo+json,application/json"})
    records=[]
    for i,site in enumerate(chosen.itertuples(index=False),1):
        counts={}
        for year in (2018,2022):
            counts[str(year)]=search_scenes(sess,site,year)
        # Note: these are distinct single-year image metadata months, not actual
        # valid same-month cloudfree pixels; month-intersection is checked later.
        common=sorted(set(counts["2018"]["selected_months"]) &
                      set(counts["2022"]["selected_months"]) &
                      {int(m) for m in str(site.original_JJA_same_calendar_months).split(",") if m})
        passed=len(common)>=2
        records.append({
          "site_key":site.site_key,"H6":site.H6,"H7":site.H7,
          "HYRIV_ID":site.HYRIV_ID,"original_lat":float(site.lat),
          "original_lon":float(site.lon),"original_reach_offset_m":float(site.original_station_to_original_reach_m),
          "original_months_TP_and_STAC_2018_2022":common,
          "source_supported_bothyear_TP_and_S2_two_common_summer_months":passed,
          "years":counts})
        if i%10==0 or i==len(chosen):
            print(f"GESUI_FR178_FIXED_SOURCE_STAC={i}/178 metadata_gate_passed={sum(q['source_supported_bothyear_TP_and_S2_two_common_summer_months'] for q in records)}",flush=True)
        time.sleep(.12)
    eligible=[r for r in records if r["source_supported_bothyear_TP_and_S2_two_common_summer_months"]]
    h7=len({r["H7"] for r in eligible});h6=len({r["H6"] for r in eligible})
    go=(len(eligible)>=120 and h7>=40 and h6>=15)
    out={
      "schema":SCHEMA,
      "status":"PASS_FR178_TRUE_RIVER_2YEAR_S2_STAC_SOURCE_ONLY" if go else "STOP_FR178_S2_STAC_SOURCE_NOT_ECOLOGY_NULL",
      "pre_vegetation_original_WQ_EQR_source_universe":263,
      "true_riverline_JJA_original_fixed_site_universe":178,
      "fixed_original_H7":58,"fixed_original_H6":23,
      "original_source_sites_tested":178,
      "true_original_TP_and_satellite_STAC_two_years_2_months_supported":len(eligible),
      "original_H7_supported":h7,"original_H6_supported":h6,
      "predeclared_minimum_sites_H7_H6":[120,40,15],
      "fully_source_blind_to_TP_EQR_NDVI_numeric_outcomes":True,
      "raster_NDVI_valid_pixel_counts_NOT_YET_CHECKED":True,
      "original_riverline_band_pixels_NOT_YET_EXTRACTED":True,
      "separate_original_France24_joint_TP_S2_pixel_gate_14_below18_REMains_STOP":True,
      "exposure_is_measured_ambient_river_TP_not_source_specific_WWTP_NP":True,
      "original_source_only_frame_sha256":sha(args.geo.read_bytes()),
      "original_STAC_collection":COLLECTION,
      "original_2018_2022_fixed_summer_months":[6,7,8],
      "original_cloud_cover_item_max_pct":40,
      "original_max_preselected_scenes_per_month_and_year":2,
      "observations":records}
    args.out.mkdir(parents=True,exist_ok=True)
    (args.out/"FR178_TWOYEAR_S2_ORIGINAL_STAC_PREPIXEL_SOURCE.json").write_text(
      json.dumps(out,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    print("GESUI_FR178_S2_SOURCE="+json.dumps({
       "status":out["status"],"n":len(eligible),"H7":h7,"H6":h6},ensure_ascii=False),flush=True)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--geo",required=True,type=pathlib.Path)
    p.add_argument("--out",required=True,type=pathlib.Path)
    run(p.parse_args())

if __name__=="__main__":main()
