SCHEMA="GESUI_20261117_FR178_SOURCE_FIRST_TRUE_REACH_JJA_S2_SCENES_V1"
API="https://earth-search.aws.element84.com/v1/search"
COLLECTION="sentinel-2-l2a"
MONTHS=(6,7,8)
MIN_SUPPORTED_H6=18
